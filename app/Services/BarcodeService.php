    /**
     * Generate SVG barcode for a given text (Code128-B).
     * @param string $text The text to encode
     * @param int $height Bar height in px
     * @param bool $showText Whether to render the text below the barcode
     * @return string SVG markup
     */
    public static function svg(string $text, int $height = 40, bool $showText = true): string
    {
        $text = strtoupper($text);
        $svg = '';

        // Start code B (104)
        $patterns = ['11010000100'];
        $checksum = 104;

        for ($i = 0; $i < strlen($text); $i++) {
            $char = $text[$i];
            $code = ord($char) - 32; // Code128-B offset
            if ($code < 0 || $code > 95) continue;

            // Get the binary pattern
            $binary = self::charToPattern($char);
            $patterns[] = $binary;
            $checksum += $code * ($i + 1);
        }

        $checksum = $checksum % 103;
        $patterns[] = self::checksumPattern($checksum);
        $patterns[] = '11000111010'; // Stop pattern

        $binary = implode('', $patterns);

        // Render SVG
        $x = 0;
        $moduleWidth = 1.5;
        $totalWidth = strlen($binary) * $moduleWidth;

        $barSvg = '';
        for ($i = 0; $i < strlen($binary); $i++) {
            if ($binary[$i] === '1') {
                $barSvg .= '<rect x="' . ($x * $moduleWidth) . '" y="0" width="' . $moduleWidth . '" height="' . $height . '" fill="#1a1a1a"/>';
            }
            $x++;
        }

        $textHeight = $showText ? 16 : 0;
        $totalHeight = $height + $textHeight;

        $svg = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ' . $totalWidth . ' ' . $totalHeight . '" width="' . $totalWidth . '" height="' . $totalHeight . '">';
        $svg .= $barSvg;
        if ($showText) {
            $svg .= '<text x="' . ($totalWidth / 2) . '" y="' . ($height + 12) . '" text-anchor="middle" font-family="\'Courier New\', monospace" font-size="9" fill="#1a1a1a">' . htmlspecialchars($text) . '</text>';
        }
        $svg .= '</svg>';

        return $svg;
    }

